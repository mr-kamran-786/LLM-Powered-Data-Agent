"""Report export (requirement F12): Markdown, HTML, Jupyter notebook and PDF.

Every export is built from the stored turns, so it contains exactly the code that was
executed and the outputs it produced: a reproducible record of the analysis.
"""

from __future__ import annotations

import base64
import html
import io
import json
import re
from datetime import datetime
from typing import Any

import pandas as pd

from backend.memory.session import Session
from backend.memory.store import store


def _turns(sess: Session) -> list[dict[str, Any]]:
    return [t for t in store.list_turns(sess.id) if t["status"] in ("answered", "failed", "clarification")]


def _title(sess: Session) -> str:
    return (store.get_session(sess.id) or {}).get("title") or "Data analysis"


def _table_md(t: dict[str, Any], max_rows: int = 20) -> str:
    df = pd.DataFrame(t["rows"][:max_rows], columns=t["columns"])
    note = f"\n\n*Showing {min(max_rows, len(t['rows']))} of {t['shape'][0]:,} rows.*" if t["shape"][0] > max_rows else ""
    return df.to_markdown(index=False, floatfmt=".4g") + note


def _code_steps(turn: dict[str, Any]) -> list[dict[str, Any]]:
    return [s for s in turn.get("steps", []) if s.get("type") in ("python", "sql")]


# ---------------------------------------------------------------- Markdown


def to_markdown(sess: Session) -> str:
    out = [f"# {_title(sess)}", "",
           f"*Generated by the Data Agent on {datetime.now():%Y-%m-%d %H:%M}.*", "", "## Datasets", ""]
    for d in sess.datasets.values():
        out.append(f"- **{d.name}** ({d.source}): {d.rows:,} rows x {d.columns} columns")
    for i, t in enumerate(_turns(sess), 1):
        out += ["", f"## {i}. {t['question']}", "", t.get("answer_md") or ""]
        steps = _code_steps(t)
        ok = [s for s in steps if s.get("ok")]
        if ok:
            out += ["", "### How this was computed", ""]
        for s in ok:
            lang = "sql" if s["type"] == "sql" else "python"
            out += [f"**{s.get('purpose') or 'Step'}**", "", f"```{lang}", s["code"].strip(), "```", ""]
            if s.get("stdout"):
                out += ["```text", s["stdout"].strip()[:3000], "```", ""]
            for tb in s.get("tables", [])[:2]:
                out += [_table_md(tb), ""]
            for c in s.get("charts", []):
                out.append(f"*Chart: {c.get('title') or 'untitled'} (interactive version in the HTML export)*")
        failed = len(steps) - len(ok)
        if failed:
            out += ["", f"*{failed} failed attempt(s) were corrected automatically.*"]
    return "\n".join(out).strip() + "\n"


# ---------------------------------------------------------------- HTML


def _md_inline(text: str) -> str:
    text = html.escape(text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<!\*)\*(?!\s)(.+?)(?<!\s)\*(?!\*)", r"<em>\1</em>", text)
    return re.sub(r"`([^`]+)`", r"<code>\1</code>", text)


def _md_block(md: str) -> str:
    lines, out, in_list = (md or "").splitlines(), [], False
    for line in lines:
        stripped = line.strip()
        if re.match(r"^[-*] ", stripped):
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append(f"<li>{_md_inline(stripped[2:])}</li>")
            continue
        if in_list:
            out.append("</ul>")
            in_list = False
        if stripped.startswith("#"):
            level = min(len(stripped) - len(stripped.lstrip("#")) + 2, 6)
            out.append(f"<h{level}>{_md_inline(stripped.lstrip('#').strip())}</h{level}>")
        elif stripped:
            out.append(f"<p>{_md_inline(stripped)}</p>")
    if in_list:
        out.append("</ul>")
    return "\n".join(out)


def _table_html(t: dict[str, Any], max_rows: int = 20) -> str:
    head = "".join(f"<th>{html.escape(str(c))}</th>" for c in t["columns"])
    body = "".join("<tr>" + "".join(f"<td>{html.escape(_fmt(v))}</td>" for v in row) + "</tr>" for row in t["rows"][:max_rows])
    cap = f"<caption>{html.escape(t.get('title') or '')} — {t['shape'][0]:,} rows</caption>"
    return f"<div class='tbl'><table>{cap}<thead><tr>{head}</tr></thead><tbody>{body}</tbody></table></div>"


def _fmt(v: Any) -> str:
    if isinstance(v, float):
        return f"{v:,.4g}" if abs(v) < 1e4 else f"{v:,.2f}"
    return "" if v is None else str(v)


def to_html(sess: Session) -> str:
    charts_js, parts, n = [], [], 0
    for i, t in enumerate(_turns(sess), 1):
        parts.append(f"<section><h2>{i}. {html.escape(t['question'])}</h2><div class='answer'>{_md_block(t.get('answer_md') or '')}</div>")
        for s in [s for s in _code_steps(t) if s.get("ok")]:
            for c in s.get("charts", []):
                if c["kind"] == "plotly":
                    n += 1
                    parts.append(f"<div class='chart' id='c{n}'></div>")
                    spec = c["spec"]
                    charts_js.append(f"Plotly.newPlot('c{n}', {json.dumps(spec.get('data', []))}, "
                                     f"{json.dumps(spec.get('layout', {}))}, {{responsive: true, displaylogo: false}});")
                else:
                    parts.append(f"<img class='chart' alt='chart' src='data:image/png;base64,{c['png']}'>")
            for tb in s.get("tables", [])[:1]:
                parts.append(_table_html(tb))
            lang = "SQL" if s["type"] == "sql" else "Python"
            parts.append(f"<details><summary>{lang}: {html.escape(s.get('purpose') or 'code')}</summary>"
                         f"<pre><code>{html.escape(s['code'])}</code></pre>"
                         + (f"<pre class='out'>{html.escape(s['stdout'][:3000])}</pre>" if s.get("stdout") else "")
                         + "</details>")
        parts.append("</section>")
    datasets = "".join(f"<li><strong>{html.escape(d.name)}</strong> — {d.rows:,} rows × {d.columns} columns</li>"
                       for d in sess.datasets.values())
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>{html.escape(_title(sess))}</title>
<script src="https://cdn.plot.ly/plotly-2.35.2.min.js"></script>
<style>body{{font:15px/1.6 system-ui,sans-serif;max-width:960px;margin:2rem auto;padding:0 1rem;color:#1d2433}}
h1{{font-size:1.8rem}}h2{{border-top:1px solid #e3e6ec;padding-top:1.2rem;font-size:1.25rem}}
.answer{{background:#f5f8ff;border-left:4px solid #3b6fe0;padding:.6rem 1rem;border-radius:6px}}
.chart{{width:100%;min-height:380px;margin:1rem 0}}img.chart{{min-height:0}}
.tbl{{overflow-x:auto}}table{{border-collapse:collapse;font-size:13px;margin:.8rem 0}}
th,td{{border:1px solid #e3e6ec;padding:4px 8px;text-align:left}}th{{background:#f3f4f7}}caption{{text-align:left;color:#667}}
pre{{background:#0f172a;color:#e2e8f0;padding:.8rem;border-radius:6px;overflow-x:auto;font-size:12.5px}}
pre.out{{background:#f3f4f7;color:#333}}summary{{cursor:pointer;color:#3b6fe0}}</style></head><body>
<h1>{html.escape(_title(sess))}</h1><p style="color:#667">Generated by the Data Agent on {datetime.now():%Y-%m-%d %H:%M}</p>
<h2>Datasets</h2><ul>{datasets}</ul>{''.join(parts)}
<script>{''.join(charts_js)}</script></body></html>"""


# ---------------------------------------------------------------- Jupyter notebook


def to_notebook(sess: Session) -> str:
    def md(text: str) -> dict:
        return {"cell_type": "markdown", "metadata": {}, "source": text.splitlines(keepends=True)}

    def code(text: str) -> dict:
        return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
                "source": text.splitlines(keepends=True)}

    setup = ["import pandas as pd, numpy as np", "import plotly.express as px, plotly.graph_objects as go",
             "import matplotlib.pyplot as plt", "from scipy import stats", "import duckdb", "",
             "def show_table(df, title=None):\n    display(df.head(50))",
             "def show_chart(fig, title=None):\n    fig.show()",
             "def sql(query):\n    return duckdb.sql(query).df()", "",
             "# Datasets: place the files next to this notebook (exported as Parquet by the Data Agent)"]
    for d in sess.datasets.values():
        if d.parquet_path is not None:
            setup.append(f"{d.name} = pd.read_parquet({d.parquet_path.name!r})")
        else:
            setup.append(f"# {d.name}: table from database connection {d.source[3:]!r}; query it with your own connection")
    cells = [md(f"# {_title(sess)}\n\nReproducible record exported by the Data Agent on {datetime.now():%Y-%m-%d %H:%M}."),
             code("\n".join(setup))]
    for i, t in enumerate(_turns(sess), 1):
        cells.append(md(f"## {i}. {t['question']}\n\n{t.get('answer_md') or ''}"))
        for s in [s for s in _code_steps(t) if s.get("ok")]:
            if s.get("purpose"):
                cells.append(md(f"*{s['purpose']}*"))
            if s["type"] == "sql":
                target = s.get("target", "files")
                if target in ("files", ""):
                    cells.append(code(f"{s.get('result_name', 'sql_result')} = sql({s['code']!r})\n{s.get('result_name', 'sql_result')}"))
                else:
                    cells.append(code(f"# SQL run against database '{target}':\nquery = {s['code']!r}"))
            else:
                cells.append(code(s["code"]))
    nb = {"cells": cells, "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                                       "language_info": {"name": "python"}}, "nbformat": 4, "nbformat_minor": 5}
    return json.dumps(nb, indent=1)


# ---------------------------------------------------------------- PDF


def to_pdf(sess: Session) -> bytes:
    from fpdf import FPDF

    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(True, margin=15)
    pdf.set_margins(15, 15, 15)
    pdf.add_page()
    width = pdf.w - 30

    def text(s: str, size: int = 10, style: str = "", mono: bool = False, h: float = 5) -> None:
        pdf.set_font("Courier" if mono else "Helvetica", style, size)
        pdf.set_x(15)
        pdf.multi_cell(width, h, _latin1(s))

    text(_title(sess), 18, "B", h=8)
    text(f"Generated by the Data Agent on {datetime.now():%Y-%m-%d %H:%M}", 9)
    pdf.ln(3)
    text("Datasets", 13, "B", h=7)
    for d in sess.datasets.values():
        text(f"- {d.name} ({d.source}): {d.rows:,} rows x {d.columns} columns", 10)
    for i, t in enumerate(_turns(sess), 1):
        pdf.ln(4)
        text(f"{i}. {t['question']}", 13, "B", h=7)
        text(re.sub(r"[*`#]", "", t.get("answer_md") or ""), 10)
        for s in [s for s in _code_steps(t) if s.get("ok")]:
            pdf.ln(2)
            text(f"{'SQL' if s['type'] == 'sql' else 'Python'}: {s.get('purpose') or ''}", 9, "B")
            text(s["code"].strip()[:2500], 7.5, mono=True, h=3.6)
            if s.get("stdout"):
                text("Output:", 8, "I")
                text(s["stdout"].strip()[:1500], 7.5, mono=True, h=3.6)
            for c in s.get("charts", []):
                if c["kind"] == "image":
                    pdf.image(io.BytesIO(base64.b64decode(c["png"])), w=min(width, 150))
                else:
                    text(f"[Interactive chart: {c.get('title') or 'untitled'} - see the HTML export]", 8, "I")
            for tb in s.get("tables", [])[:1]:
                cols = tb["columns"][:6]
                rows = [r[:6] for r in tb["rows"][:12]]
                pdf.set_font("Helvetica", "", 7.5)
                with pdf.table(col_widths=[width / len(cols)] * len(cols), text_align="LEFT", line_height=4.2) as table:
                    table.row([_latin1(str(c))[:28] for c in cols])
                    for r in rows:
                        table.row([_latin1(_fmt(v))[:28] for v in r])
    return bytes(pdf.output())


def _latin1(s: str) -> str:
    """Core PDF fonts are Latin-1; replace what they cannot encode."""
    s = s.replace("—", "-").replace("–", "-").replace("’", "'").replace("“", '"').replace("”", '"')
    return s.encode("latin-1", "replace").decode("latin-1")
